class TestNicIrpEinvoiceQtyRate(unittest.TestCase):
    def test_detects_nic_irp_not_other_formats(self):
        self.assertTrue(_ocr_suggests_nic_irp_einvoice_table(NIC_IRP_OCR))
        self.assertFalse(_ocr_suggests_gst_portal_goods_details(NIC_IRP_OCR))
        self.assertFalse(_ocr_suggests_nic_irp_einvoice_table(JACKSON_OCR))
        self.assertFalse(_ocr_suggests_nic_irp_einvoice_table(STRUCTURED_EINVOICE_OCR))

    def test_parses_vault_and_pantodac_qty_rate(self):
        rows = _parse_nic_irp_einvoice_qty_rate_rows(NIC_IRP_OCR)
        by_name = {
            re_key: r for r in rows
            for re_key in [r["product_description"].upper()]
        }
        vault = next(r for r in rows if "VAULT" in r["product_description"].upper())
        panto = next(r for r in rows if "PANTODAC" in r["product_description"].upper())
        self.assertEqual(vault["quantity"], 100)
        self.assertAlmostEqual(vault["unit_price"], 111.33, places=2)
        self.assertEqual(panto["quantity"], 54)
        self.assertAlmostEqual(panto["unit_price"], 188.41, places=2)
        self.assertTrue(by_name)

    def test_corrects_taxable_total_used_as_qty_rate(self):
        items = [
            {
                "product_description": "VAULT 20 TAB 10's",
                "hsn_code": "30049099",
                "quantity": "11133",
                "unit_price": "11338.96",
                "total_amount": "11338.96",
            },
            {
                "product_description": "PANTODAC DSR CAP's 15's",
                "hsn_code": "30049039",
                "quantity": "10174.14",
                "unit_price": "10362.36",
                "total_amount": "10362.36",
            },
            {
                "product_description": "CONCOR 5MG TAB 10'S",
                "hsn_code": "30049079",
                "quantity": "200",
                "unit_price": "110.77",
                "total_amount": "22563.85",
            },
        ]
        fixed = fix_nic_irp_einvoice_qty_rate_from_ocr(items, NIC_IRP_OCR)
        vault = next(i for i in fixed if "VAULT" in i["product_description"].upper())
        panto = next(i for i in fixed if "PANTODAC" in i["product_description"].upper())
        concor = next(i for i in fixed if "CONCOR" in i["product_description"].upper())
        self.assertEqual(str(vault["quantity"]), "100")
        self.assertEqual(vault["unit_price"], "111.33")
        self.assertEqual(str(panto["quantity"]), "54")
        self.assertEqual(panto["unit_price"], "188.41")
        self.assertEqual(str(concor["quantity"]), "200")
        self.assertEqual(concor["unit_price"], "110.77")

    def test_detects_item_table_without_signature_page(self):
        """CR-2403 pages 1-3 have the table; NIC-IRP signature is often page 4."""
        table_only = NIC_IRP_OCR.replace(
            "Digitally Signed by NIC-IRP\non: 18/06/2026 09:27:00",
            "",
        )
        table_only = (
            "1.e-Invoice Details\nDocument No. : CR-2403\n"
            "4A.Details of Goods / Services\n"
            + table_only
        )
        self.assertTrue(_ocr_suggests_nic_irp_einvoice_table(table_only))
        items = [{
            "product_description": "VAULT 20 TAB 10's",
            "hsn_code": "30049099",
            "quantity": "11133",
            "unit_price": "11338.96",
            "total_amount": "11338.96",
        }]
        fixed = fix_nic_irp_einvoice_qty_rate_from_ocr(items, table_only)
        self.assertEqual(str(fixed[0]["quantity"]), "100")
        self.assertEqual(fixed[0]["unit_price"], "111.33")

