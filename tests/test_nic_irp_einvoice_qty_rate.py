    def test_keeps_plumber_table_over_garbled_tesseract(self):
        tesseract = (
            "Sr Item HSN Quantity Unit Unit Price Discount Taxable "
            "DOLONEX- 300490 10239.5 10428.93 DT 20 mg 66 "
            "VAULT 20 300490 11133 11338.96 TAB 10's 99"
        )
        self.assertTrue(_nic_irp_table_ocr_is_richer(NIC_IRP_OCR, tesseract))
        self.assertFalse(_nic_irp_table_ocr_is_richer(tesseract, NIC_IRP_OCR))
        self.assertFalse(_nic_irp_table_ocr_is_richer(JACKSON_OCR, tesseract))

    def test_does_not_touch_non_nic_items(self):
        items = [{
            "product_description": "AMLOPIN 5MG TAB",
            "quantity": "10",
            "unit_price": "20.32",
            "total_amount": "203.20",
        }]
        fixed = fix_nic_irp_einvoice_qty_rate_from_ocr(items, JACKSON_OCR)
        self.assertEqual(fixed[0]["quantity"], "10")
        self.assertEqual(fixed[0]["unit_price"], "20.32")


